import streamlit as st
import pandas as pd

# -----------------------------
# بيانات الإدارات التعليمية
# -----------------------------
data = {
    "الإدارة": ["أسوان", "دراو", "نصر", "كوم أمبو", "إدفو"],
    "عدد المدارس": [85, 21, 43, 77, 106],
    "عدد الفصول": [756, 193, 216, 719, 742],
    "عدد الطلاب": [30225, 8014, 7617, 29003, 28140]
}

df = pd.DataFrame(data)
df["كثافة الفصل"] = df["عدد الطلاب"] / df["عدد الفصول"]

# -----------------------------
# واجهة التطبيق
# -----------------------------
st.set_page_config(page_title="لوحة مؤشرات المرحلة الإعدادية – أسوان", layout="wide")
st.title("📊 لوحة مؤشرات المرحلة الإعدادية – محافظة أسوان")

# اختيار الإدارة
admin = st.selectbox("اختر الإدارة التعليمية:", ["الكل"] + list(df["الإدارة"]))

if admin != "الكل":
    df_view = df[df["الإدارة"] == admin]
else:
    df_view = df

# -----------------------------
# مؤشرات رقمية
# -----------------------------
col1, col2, col3 = st.columns(3)
col1.metric("🏫 عدد المدارس", int(df_view["عدد المدارس"].sum()))
col2.metric("📚 عدد الفصول", int(df_view["عدد الفصول"].sum()))
col3.metric("👨‍🎓 عدد الطلاب", int(df_view["عدد الطلاب"].sum()))

st.divider()

