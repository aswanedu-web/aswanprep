# -----------------------------
# مؤشرات التحذير
# -----------------------------
st.subheader("🚦 مؤشرات التحذير")
def traffic_light(x):
    if x >= 40:
        return "🔴 مرتفع"
    elif x >= 35:
        return "🟡 متوسط"
    else:
        return "🟢 آمن"

df["مؤشر"] = df["كثافة الفصل"].apply(traffic_light)
st.dataframe(df[["الإدارة", "كثافة الفصل", "مؤشر"]])

# -----------------------------
# ترتيب الإدارات حسب العبء
# -----------------------------
st.subheader("📌 ترتيب الإدارات من الأعلى إلى الأقل عبئًا")
df_sorted = df.sort_values("كثافة الفصل", ascending=False)
st.table(df_sorted[["الإدارة", "كثافة الفصل"]])
